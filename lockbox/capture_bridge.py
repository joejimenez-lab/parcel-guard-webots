"""Loopback transport for recording the real control page against Webots.

The capture client advances the simulator one step at a time. Commands still
come from the page's form/button handlers and reach the normal controller.
No sensor status or access outcome is generated by the browser.
"""
import json
import queue
import secrets
import threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path


class CaptureBridge:
    def __init__(self, root, name, frames, schedule):
        self.commands = queue.Queue()
        self.token = secrets.token_urlsafe(24)
        self.status = None
        self.received = []
        bridge = self

        class Handler(SimpleHTTPRequestHandler):
            def __init__(self, *args, **kwargs):
                super().__init__(*args, directory=str(root), **kwargs)

            def log_message(self, *args):
                pass

            def reply(self, data, code=200):
                body = json.dumps(data).encode()
                self.send_response(code)
                self.send_header('Content-Type', 'application/json')
                self.send_header('Content-Length', str(len(body)))
                self.send_header('Cache-Control', 'no-store')
                self.end_headers()
                self.wfile.write(body)

            def authorized(self):
                return self.headers.get('X-Capture-Token') == bridge.token

            def do_GET(self):
                if self.path == '/capture/status':
                    if not self.authorized():
                        return self.reply({'error': 'unauthorized'}, 403)
                    return self.reply(bridge.status)
                super().do_GET()

            def do_POST(self):
                if not self.authorized():
                    return self.reply({'error': 'unauthorized'}, 403)
                if self.path == '/capture/command':
                    command = json.loads(self.rfile.read(int(self.headers['Content-Length'])))
                    bridge.received.append(command)
                    bridge.commands.put(('command', command))
                    return self.reply({'accepted': True})
                if self.path == '/capture/step':
                    done = threading.Event()
                    bridge.commands.put(('step', done))
                    if not done.wait(60):
                        return self.reply({'error': 'simulator step timed out'}, 504)
                    return self.reply(bridge.status)
                self.reply({'error': 'not found'}, 404)

        self.server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        destination = Path(root) / '.build' / 'ui-capture' / f'{name}.json'
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(json.dumps({
            'url': f'http://127.0.0.1:{self.server.server_port}',
            'token': self.token, 'frames': frames, 'schedule': schedule,
        }))

    def before_step(self, harness):
        while True:
            kind, data = self.commands.get(timeout=180)
            if kind == 'command':
                harness.send(**data)
            else:
                return data

    def after_step(self, harness, done):
        self.status = harness.latest
        done.set()

    def close(self):
        self.server.shutdown()
        self.server.server_close()
